import { legal } from "@synoro/config";

const BOM = String.fromCharCode(0xfeff);

/** Line breaks are CRLF: the guide is opened in Windows Notepad as often as not. */
function lines(text: string) {
  return `${BOM}${text.trim().replace(/\n/g, "\r\n")}\r\n`;
}

export const README_FULL = lines(`
Ваши данные из Synoro

В этом архиве всё, что вы вели в Synoro: клиенты, записи, услуги и оплаты.
Данные принадлежат вам. Распоряжайтесь ими как хотите.

В архиве есть данные ваших клиентов. Храните его там, куда нет доступа у других
людей, и не пересылайте без необходимости.


Что лежит в архиве

clients.csv        Клиенты: имя, телефон, почта, баланс. Сюда же входят гости,
                   которых вы записывали по имени и телефону.
appointments.csv   Все записи, в том числе прошедшие и отменённые, а также
                   закрытое время: дата, клиент, статус, комментарий, анкета.
services.csv       Услуги: основное занятие, бесплатная услуга, пакеты с ценами.
payments.csv       Онлайн-оплаты клиентов и ваши оплаты тарифа «Про».
calendar.ics       Все записи в формате календаря.
data.json          Всё то же самое и настройки практики для загрузки в программы:
                   рабочие часы, анкета, сообщения клиентам, журнал баланса.
README.txt         Этот файл.

Даты указаны в часовом поясе практики в виде ДД.ММ.ГГГГ ЧЧ:ММ.


Как открыть в Excel

Дважды щёлкните по файлу .csv. Русские буквы и колонки встанут на место.
Если значение в ячейке начинается с апострофа, так и задумано: это защита
от случайного запуска формулы из текста, который ввёл клиент.


Как добавить записи в календарь

Google Календарь: «Настройки» → «Импорт и экспорт» → выберите calendar.ics.
Яндекс Календарь: импортируйте файл calendar.ics в настройках календаря.

Это разовая копия. Чтобы календарь обновлялся сам, включите подписку
в Synoro: «Настройки» → «Ваши данные».


Как перенести данные в другой сервис

Клиенты. Почти любой сервис записи умеет загружать таблицу. Загрузите туда
clients.csv и сопоставьте колонки «Имя», «Телефон», «Почта или контакт».

Записи. Если сервис не принимает appointments.csv, загрузите calendar.ics
в его календарь.

Для разработчиков. В data.json есть все связи по идентификаторам и поле
format_version с номером версии формата.


Как вернуться в Synoro

Загрузите data.json в аккаунт Synoro: клиенты, записи и настройки появятся снова.
Старые архивы подходят тоже. Если что-то непонятно, напишите нам:
${legal.operator.email}
`);

