/** `first` replaces the generic opening question on a profession's page. */
export function Faq({ first }: { first?: (typeof questions)[number] }) {
  const items = first ? [first, ...questions.slice(1)] : questions;
  return (
    <Section
      id="faq"
      containerClassName="grid gap-10 px-4 py-16 sm:px-10 sm:py-24 lg:grid-cols-[1fr_1.4fr]"
    >
      <JsonLd data={faqPage(items)} />
      <div className="flex flex-col gap-5 lg:sticky lg:top-24 lg:self-start">
        <SectionHeading>Частые вопросы</SectionHeading>
        <Lead>
          Не нашли ответ? Напишите нам — поможем настроить практику и перенести
          клиентов.
        </Lead>
      </div>
      <Accordion className="border-t">
        {items.map((item) => (
          <AccordionItem key={item.q} value={item.q}>
            <AccordionTrigger className="py-5 text-base hover:no-underline">
              {item.q}
            </AccordionTrigger>
            {/* Mounted while closed: search engines read the answers. */}
            <AccordionContent
              keepMounted
              className="text-muted-foreground pr-8 text-[15px] leading-relaxed"
            >
              {item.a}
            </AccordionContent>
          </AccordionItem>
        ))}
      </Accordion>
    </Section>
  );
}
