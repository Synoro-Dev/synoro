/**
 * Landing pages for one profession each (`/solutions/<slug>`): the pages Yandex
 * Direct campaigns lead to (docs/direct-campaigns.md). The words follow the
 * profession profiles of the app (`PROFESSION_TERMS` in `@synoro/validators`):
 * the landing stays free of that dependency, so keep them in sync by hand.
 *
 * The copy promises only what the product does today: the paid booking lasts
 * 60 minutes, group sessions are not supported (docs/beyond-psychologists.md).
 */

export type ProfessionPage = {
  /** `/solutions/<slug>`; also `utm_campaign` of the Direct campaign. */
  slug: string;
  /** The `Profession` of the app this page speaks for. */
  profile: "psychologist" | "coach" | "legal" | "tutor" | "trainer" | "health";
  /** In the audience list and in links to the page. */
  audience: string;
  /** Page title, before « · Synoro». */
  title: string;
  description: string;
  /** What the page is, in the words people search for: the `<h1>`. */
  h1: string;
  /** The two big lines of the hero. */
  heading: readonly [string, string];
  lead: string;
  /** The booking page shown in the hero, in the profession's words. */
  demo: {
    name: string;
    host: string;
    service: string;
    /** Genitive plural after a number: «осталось 6 консультаций». */
    many: string;
  };
  /** Three things this profession cares about. */
  pointsHeading: string;
  points: readonly { title: string; text: string }[];
  /** Replaces the first, generic question of the FAQ. */
  question: { q: string; a: string };
};

