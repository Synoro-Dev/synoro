function planPrice(plan: (typeof plans)[number]) {
  if (plan.custom) return "по отдельному соглашению";
  if (plan.monthly === null) return "0 ₽";
  const base = plan.yearly
    ? `${rubles(plan.monthly)} в месяц или ${rubles(plan.yearly)} в год`
    : `${rubles(plan.monthly)} в месяц`;
  return plan.trialDays
    ? `${base}; первые ${plan.trialDays} дней бесплатно`
    : base;
}

